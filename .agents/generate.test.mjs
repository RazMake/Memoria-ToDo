import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';

const generator = join(dirname(fileURLToPath(import.meta.url)), 'generate.mjs');
const role = {
  description: 'Help with a "quoted" task: use one source.\nRead the docs.',
  readOnly: false,
  claude: { model: 'native-model', effort: 'medium' },
  codex: { model: 'codex-model', effort: 'high' },
  copilot: { model: ['copilot-model', 'Display Model (copilot)'], effort: 'xhigh' },
};
const profiles = [
  ['.claude', 'agents', 'helper.md'],
  ['.codex', 'agents', 'helper.toml'],
  ['.github', 'agents', 'helper.agent.md'],
];

function fixture(t, roles = { helper: role }) {
  const root = mkdtempSync(join(tmpdir(), 'memoria-generator-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const source = join(root, '.agents', 'subagents');
  mkdirSync(source, { recursive: true });
  copyFileSync(generator, join(root, '.agents', 'generate.mjs'));
  writeFileSync(join(source, 'subagents.json'), JSON.stringify(roles));
  for (const name of Object.keys(roles)) {
    writeFileSync(join(source, `${name}.md`), 'These instructions must stay in the shared source.\n');
  }
  return {
    path: (...parts) => join(root, ...parts),
    read: (...parts) => readFileSync(join(root, ...parts), 'utf8'),
    write: (parts, content) => writeFileSync(join(root, ...parts), content),
    run: (...args) => {
      const result = spawnSync(process.execPath, [join(root, '.agents', 'generate.mjs'), ...args], {
        cwd: root,
        encoding: 'utf8',
        timeout: 30_000,
      });
      assert.ifError(result.error);
      return result;
    },
  };
}

function succeeds(result) {
  assert.equal(result.status, 0, result.stderr);
}

function rejectsBeforeWriting(files, result, message) {
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stderr, message);
  for (const [tool, dir] of profiles) {
    assert.equal(existsSync(files.path(tool, dir)), false, `${tool}: no output before validation succeeds`);
  }
}

describe('agent generator (integration)', () => {
  test('generates metadata for every runtime and points to the shared instructions', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    const claude = files.read(...profiles[0]);
    const codex = files.read(...profiles[1]);
    const copilot = files.read(...profiles[2]);

    for (const output of [claude, copilot]) {
      assert.ok(output.startsWith('---\n# Generated by .agents/generate.mjs from .agents/subagents/'));
      assert.ok(output.includes('\nname: "helper"\n'));
      assert.ok(output.includes('\ndescription: "Help with a \\"quoted\\" task: use one source.\\nRead the docs."\n'));
      assert.ok(!output.includes('\ndisallowedTools:'));
      assert.ok(!output.includes('\ntools:'));
    }
    assert.ok(claude.includes('\nmodel: "native-model"\n'));
    assert.ok(claude.includes('\neffort: "medium"\n'));
    assert.ok(codex.includes('\nname = "helper"\n'));
    assert.ok(codex.includes('\ndescription = "Help with a \\"quoted\\" task: use one source.\\nRead the docs."\n'));
    assert.ok(codex.includes('\nmodel = "codex-model"\n'));
    assert.ok(codex.includes('\nmodel_reasoning_effort = "high"\n'));
    assert.ok(codex.includes('\ndeveloper_instructions = """\n'));
    assert.ok(copilot.includes('\nmodel: ["copilot-model","Display Model (copilot)"]\n'));
    assert.ok(copilot.includes('\nreasoning-effort: "xhigh"\n'));
    assert.ok(copilot.includes('\ninclude-custom-instructions: true\n'));
    for (const output of [claude, codex, copilot]) {
      assert.ok(output.includes('Your instructions are in `.agents/subagents/helper.md`. Read that whole file before doing anything else, then follow it exactly.'));
      assert.ok(!output.includes('These instructions must stay in the shared source.'));
    }
  });

  test('omits effort fields when unset and accepts a single Copilot model', (t) => {
    const files = fixture(t, {
      helper: {
        ...role,
        claude: { model: 'native-model' },
        codex: { model: 'codex-model' },
        copilot: { model: 'copilot-model' },
      },
    });
    succeeds(files.run());
    assert.ok(!files.read(...profiles[0]).includes('\neffort:'));
    assert.ok(!files.read(...profiles[1]).includes('\nmodel_reasoning_effort ='));
    const copilot = files.read(...profiles[2]);
    assert.ok(!copilot.includes('\nreasoning-effort:'));
    assert.ok(copilot.includes('\nmodel: "copilot-model"\n'));
  });

  test('limits read-only roles in Claude and Copilot while Codex inherits its sandbox', (t) => {
    const files = fixture(t, { helper: { ...role, readOnly: true } });
    succeeds(files.run());
    assert.ok(files.read(...profiles[0]).includes('\ndisallowedTools: "Write, Edit, NotebookEdit"\n'));
    assert.ok(files.read(...profiles[2]).includes('\ntools: ["read","search","execute"]\n'));
    assert.ok(!files.read(...profiles[1]).includes('sandbox_mode'));
  });

  test('accepts current profiles in check mode', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    const before = profiles.map((path) => files.read(...path));
    succeeds(files.run('--check'));
    assert.deepEqual(profiles.map((path) => files.read(...path)), before);
  });

  test('detects drift without writing and repairs it on generation', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    const before = profiles.map((path) => files.read(...path));
    rmSync(files.path(...profiles[0]));
    files.write(profiles[2], 'Locally edited profile.\n');

    const result = files.run('--check');
    assert.equal(result.status, 1, result.stderr);
    assert.match(result.stderr, /out of date: \.claude\/agents\/helper\.md/);
    assert.match(result.stderr, /out of date: \.github\/agents\/helper\.agent\.md/);
    assert.equal(existsSync(files.path(...profiles[0])), false);
    assert.equal(files.read(...profiles[2]), 'Locally edited profile.\n');

    succeeds(files.run());
    assert.deepEqual(profiles.map((path) => files.read(...path)), before);
    succeeds(files.run('--check'));
  });

  test('removes obsolete generated profiles without deleting hand-written files', (t) => {
    const files = fixture(t, { helper: role, retired: role });
    succeeds(files.run());
    const retired = profiles.map(([tool, dir, name]) => [tool, dir, name.replace('helper', 'retired')]);
    const manual = profiles.map(([tool, dir, name]) => [tool, dir, name.replace('helper', 'manual')]);
    for (const path of manual) files.write(path, 'Hand-written agent configuration.\n');
    files.write(['.agents', 'subagents', 'subagents.json'], JSON.stringify({ helper: role }));

    const result = files.run('--check');
    assert.equal(result.status, 1, result.stderr);
    for (const path of retired) {
      assert.ok(result.stderr.includes(`stale: ${path.join('/')}`));
      assert.equal(existsSync(files.path(...path)), true);
    }
    succeeds(files.run());
    for (const path of retired) assert.equal(existsSync(files.path(...path)), false);
    for (const path of manual) assert.equal(files.read(...path), 'Hand-written agent configuration.\n');
    succeeds(files.run('--check'));
  });

  test('rejects an empty Copilot effort before writing even a preceding valid role', (t) => {
    const files = fixture(t, {
      first: role,
      helper: { ...role, copilot: { ...role.copilot, effort: '' } },
    });
    rejectsBeforeWriting(files, files.run(), /invalid copilot\.effort/);
  });

  test('rejects unknown runtime settings before writing profiles', (t) => {
    const files = fixture(t, {
      helper: { ...role, copilot: { ...role.copilot, unsupported: 'high' } },
    });
    rejectsBeforeWriting(files, files.run(), /copilot doesn't support "unsupported"/);
  });

  test('rejects a missing shared instructions file before writing profiles', (t) => {
    const files = fixture(t);
    rmSync(files.path('.agents', 'subagents', 'helper.md'));
    rejectsBeforeWriting(files, files.run(), /missing instructions file/);
  });

  test('rejects unknown command-line arguments before writing profiles', (t) => {
    const files = fixture(t);
    rejectsBeforeWriting(files, files.run('--unknown'), /unknown argument; usage:/);
  });
});
