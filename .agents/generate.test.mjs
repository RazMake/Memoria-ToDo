import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';

const generator = join(dirname(fileURLToPath(import.meta.url)), 'generate.mjs');
// Contract for the unit tests: importing generate.mjs runs nothing, and it exports
//   skillPointer(folderName: string, source: string): string
// which returns the text of .claude/skills/<folderName>/SKILL.md for the SKILL.md text `source`, or throws an Error whose
// message names the skill (its folder name) and the problem. generate.mjs stays one file, since the integration tests copy only it.
const { skillPointer } = await import('./generate.mjs');
const role = {
  description: 'Help with a "quoted" task: use one source.\nRead the docs.',
  readOnly: false,
  claude: { model: 'native-model', effort: 'medium' },
  codex: { model: 'codex-model', effort: 'high' },
  copilot: { model: ['copilot-model', 'Display Model (copilot)'], effort: 'xhigh' },
};
const profiles = [
  ['.claude', 'agents', 'helper.md'],
  ['.codex', 'agents', 'helper.toml'],
  ['.github', 'agents', 'helper.agent.md'],
];

// `skills` maps a folder name under .agents/skills/ to its SKILL.md text, or to null for a folder without SKILL.md.
function fixture(t, roles = { helper: role }, skills = {}) {
  const root = mkdtempSync(join(tmpdir(), 'memoria-generator-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const source = join(root, '.agents', 'subagents');
  mkdirSync(source, { recursive: true });
  copyFileSync(generator, join(root, '.agents', 'generate.mjs'));
  writeFileSync(join(source, 'subagents.json'), JSON.stringify(roles));
  for (const name of Object.keys(roles)) {
    writeFileSync(join(source, `${name}.md`), 'These instructions must stay in the shared source.\n');
  }
  for (const [name, text] of Object.entries(skills)) {
    mkdirSync(join(root, '.agents', 'skills', name), { recursive: true });
    if (text !== null) writeFileSync(join(root, '.agents', 'skills', name, 'SKILL.md'), text);
  }
  return {
    path: (...parts) => join(root, ...parts),
    read: (...parts) => readFileSync(join(root, ...parts), 'utf8'),
    write: (parts, content) => writeFileSync(join(root, ...parts), content),
    run: (...args) => {
      const result = spawnSync(process.execPath, [join(root, '.agents', 'generate.mjs'), ...args], {
        cwd: root,
        encoding: 'utf8',
        timeout: 30_000,
      });
      assert.ifError(result.error);
      return result;
    },
  };
}

function succeeds(result) {
  assert.equal(result.status, 0, result.stderr);
}

function rejectsBeforeWriting(files, result, message) {
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stderr, message);
  for (const [tool, dir] of profiles) {
    assert.equal(existsSync(files.path(tool, dir)), false, `${tool}: no output before validation succeeds`);
  }
}

describe('agent generator (integration)', () => {
  test('generates metadata for every runtime and points to the shared instructions', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    const claude = files.read(...profiles[0]);
    const codex = files.read(...profiles[1]);
    const copilot = files.read(...profiles[2]);

    for (const output of [claude, copilot]) {
      assert.ok(output.startsWith('---\n# Generated by .agents/generate.mjs from .agents/subagents/'));
      assert.ok(output.includes('\nname: "helper"\n'));
      assert.ok(output.includes('\ndescription: "Help with a \\"quoted\\" task: use one source.\\nRead the docs."\n'));
      assert.ok(!output.includes('\ndisallowedTools:'));
    }
    assert.ok(!claude.includes('\ntools:'));
    assert.ok(claude.includes('\nmodel: "native-model"\n'));
    assert.ok(claude.includes('\neffort: "medium"\n'));
    assert.ok(codex.includes('\nname = "helper"\n'));
    assert.ok(codex.includes('\ndescription = "Help with a \\"quoted\\" task: use one source.\\nRead the docs."\n'));
    assert.ok(codex.includes('\nmodel = "codex-model"\n'));
    assert.ok(codex.includes('\nmodel_reasoning_effort = "high"\n'));
    assert.ok(codex.includes('\ndeveloper_instructions = """\n'));
    assert.ok(copilot.includes('\nmodel: ["copilot-model","Display Model (copilot)"]\n'));
    assert.ok(copilot.includes('\nreasoning-effort: "xhigh"\n'));
    assert.ok(copilot.includes('\ninclude-custom-instructions: true\n'));
    for (const output of [claude, codex, copilot]) {
      assert.ok(output.includes('Your instructions are in `.agents/subagents/helper.md`. Read that whole file before doing anything else, then follow it exactly.'));
      assert.ok(!output.includes('These instructions must stay in the shared source.'));
    }
  });

  test('omits effort fields when unset and accepts a single Copilot model', (t) => {
    const files = fixture(t, {
      helper: {
        ...role,
        claude: { model: 'native-model' },
        codex: { model: 'codex-model' },
        copilot: { model: 'copilot-model' },
      },
    });
    succeeds(files.run());
    assert.ok(!files.read(...profiles[0]).includes('\neffort:'));
    assert.ok(!files.read(...profiles[1]).includes('\nmodel_reasoning_effort ='));
    const copilot = files.read(...profiles[2]);
    assert.ok(!copilot.includes('\nreasoning-effort:'));
    assert.ok(copilot.includes('\nmodel: "copilot-model"\n'));
  });

  test('lists editing and web tools for writable Copilot roles instead of inheriting the main session tools', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    assert.ok(files.read(...profiles[2]).includes('\ntools: ["read","edit","search","execute","web"]\n'));
  });

  test('limits read-only roles in Claude and Copilot while Codex inherits its sandbox', (t) => {
    const files = fixture(t, { helper: { ...role, readOnly: true } });
    succeeds(files.run());
    assert.ok(files.read(...profiles[0]).includes('\ndisallowedTools: "Write, Edit, NotebookEdit"\n'));
    assert.ok(files.read(...profiles[2]).includes('\ntools: ["read","search","execute"]\n'));
    assert.ok(!files.read(...profiles[1]).includes('sandbox_mode'));
  });

  test('accepts current profiles in check mode', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    const before = profiles.map((path) => files.read(...path));
    succeeds(files.run('--check'));
    assert.deepEqual(profiles.map((path) => files.read(...path)), before);
  });

  test('detects drift without writing and repairs it on generation', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    const before = profiles.map((path) => files.read(...path));
    rmSync(files.path(...profiles[0]));
    files.write(profiles[2], 'Locally edited profile.\n');

    const result = files.run('--check');
    assert.equal(result.status, 1, result.stderr);
    assert.match(result.stderr, /out of date: \.claude\/agents\/helper\.md/);
    assert.match(result.stderr, /out of date: \.github\/agents\/helper\.agent\.md/);
    assert.equal(existsSync(files.path(...profiles[0])), false);
    assert.equal(files.read(...profiles[2]), 'Locally edited profile.\n');

    succeeds(files.run());
    assert.deepEqual(profiles.map((path) => files.read(...path)), before);
    succeeds(files.run('--check'));
  });

  test('removes obsolete generated profiles without deleting hand-written files', (t) => {
    const files = fixture(t, { helper: role, retired: role });
    succeeds(files.run());
    const retired = profiles.map(([tool, dir, name]) => [tool, dir, name.replace('helper', 'retired')]);
    const manual = profiles.map(([tool, dir, name]) => [tool, dir, name.replace('helper', 'manual')]);
    for (const path of manual) files.write(path, 'Hand-written agent configuration.\n');
    files.write(['.agents', 'subagents', 'subagents.json'], JSON.stringify({ helper: role }));

    const result = files.run('--check');
    assert.equal(result.status, 1, result.stderr);
    for (const path of retired) {
      assert.ok(result.stderr.includes(`stale: ${path.join('/')}`));
      assert.equal(existsSync(files.path(...path)), true);
    }
    succeeds(files.run());
    for (const path of retired) assert.equal(existsSync(files.path(...path)), false);
    for (const path of manual) assert.equal(files.read(...path), 'Hand-written agent configuration.\n');
    succeeds(files.run('--check'));
  });

  test('rejects an empty Copilot effort before writing even a preceding valid role', (t) => {
    const files = fixture(t, {
      first: role,
      helper: { ...role, copilot: { ...role.copilot, effort: '' } },
    });
    rejectsBeforeWriting(files, files.run(), /invalid copilot\.effort/);
  });

  test('rejects unknown runtime settings before writing profiles', (t) => {
    const files = fixture(t, {
      helper: { ...role, copilot: { ...role.copilot, unsupported: 'high' } },
    });
    rejectsBeforeWriting(files, files.run(), /copilot doesn't support "unsupported"/);
  });

  test('rejects a missing shared instructions file before writing profiles', (t) => {
    const files = fixture(t);
    rmSync(files.path('.agents', 'subagents', 'helper.md'));
    rejectsBeforeWriting(files, files.run(), /missing instructions file/);
  });

  test('rejects unknown command-line arguments before writing profiles', (t) => {
    const files = fixture(t);
    rejectsBeforeWriting(files, files.run('--unknown'), /unknown argument; usage:/);
  });
});

const skillText = (name, body = 'Secret instructions that must stay in the source.') =>
  `---\nname: ${name}\ndescription: Does ${name} work. Use when asked to do ${name}.\nlicense: MIT\nmetadata-note: "kept: as written"\n---\n\n# ${name}\n\n${body}\n`;
const pointerPath = (name) => ['.claude', 'skills', name, 'SKILL.md'];

describe('skill pointer text (unit)', () => {
  const source = skillText('alpha');
  const frontmatter = ['name: alpha', 'description: Does alpha work. Use when asked to do alpha.', 'license: MIT', 'metadata-note: "kept: as written"'];

  test('starts with the generated-file marker naming the skill source inside the frontmatter', () => {
    const pointer = skillPointer('alpha', source).split('\n');
    assert.equal(pointer[0], '---');
    assert.ok(pointer[1].startsWith('# Generated by .agents/generate.mjs from .agents/skills/alpha/SKILL.md.'), pointer[1]);
  });

  test('keeps the source\'s whole frontmatter unchanged', () => {
    const pointer = skillPointer('alpha', source).split('\n');
    assert.deepEqual(pointer.slice(2, 2 + frontmatter.length), frontmatter);
    assert.equal(pointer[2 + frontmatter.length], '---');
  });

  test('has one line after the frontmatter, pointing to the source', () => {
    const pointer = skillPointer('alpha', source).split('\n');
    const body = pointer.slice(3 + frontmatter.length).filter((line) => line.trim() !== '');
    assert.equal(body.length, 1);
    assert.ok(body[0].includes('.agents/skills/alpha/SKILL.md'));
  });

  test('ends with one newline', () => {
    const pointer = skillPointer('alpha', source);
    assert.ok(pointer.endsWith('\n') && !pointer.endsWith('\n\n'));
  });

  test('holds none of the instructions', () => {
    const pointer = skillPointer('alpha', source);
    assert.ok(!pointer.includes('Secret instructions'));
    assert.ok(!pointer.includes('# alpha'));
  });

  test('gives the same pointer for Windows and Unix line endings', () => {
    assert.equal(skillPointer('alpha', source.replaceAll('\n', '\r\n')), skillPointer('alpha', source));
    assert.ok(!skillPointer('alpha', source.replaceAll('\n', '\r\n')).includes('\r'));
  });

  test('accepts a name with digits and single hyphens', () => {
    assert.doesNotThrow(() => skillPointer('a1-b2-c3', skillText('a1-b2-c3')));
  });
});

describe('skill rejections (unit)', () => {
  const rejects = (what, folder, source, problem) =>
    test(`rejects ${what}, naming the skill and the problem`, () => {
      assert.throws(() => skillPointer(folder, source), (error) => {
        assert.ok(error instanceof Error);
        assert.ok(error.message.includes(folder), error.message);
        assert.match(error.message, problem);
        return true;
      });
    });

  rejects('a file with no frontmatter', 'alpha', '# alpha\n\nJust text.\n', /frontmatter/);
  rejects('frontmatter that never closes', 'alpha', '---\nname: alpha\ndescription: Does alpha.\n\nText.\n', /frontmatter/);
  rejects('an empty file', 'alpha', '', /frontmatter/);
  rejects('a missing description', 'alpha', '---\nname: alpha\n---\n\nText.\n', /description/);
  rejects('an empty description', 'alpha', '---\nname: alpha\ndescription:\n---\n\nText.\n', /description/);
  rejects('a blank description', 'alpha', '---\nname: alpha\ndescription:    \n---\n\nText.\n', /description/);
  rejects('a missing name', 'alpha', '---\ndescription: Does alpha.\n---\n\nText.\n', /name/);
  rejects('a name that is not the folder\'s name', 'alpha', skillText('beta'), /name/);
  for (const bad of ['Bad_Name', 'Upper', '-lead', 'trail-', 'double--hyphen', 'a'.repeat(65), 'sp ace']) {
    rejects(`the name "${bad.length > 20 ? 'a x65' : bad}", which breaks the naming rule even though it matches its folder`, bad, skillText(bad), /name/);
  }
  rejects('a description folded over several lines', 'alpha', '---\nname: alpha\ndescription: >\n  Does alpha\n  work.\n---\n\nText.\n', /one line/);
  rejects('a description continued on the next line', 'alpha', '---\nname: alpha\ndescription: Does alpha\n  and more.\n---\n\nText.\n', /one line/);
  rejects('a name that is not on one line', 'alpha', '---\nname: >\n  alpha\ndescription: Does alpha.\n---\n\nText.\n', /one line/);

  const withDescription = (value) => `---\nname: alpha\ndescription: ${value}\n---\n\nText.\n`;
  const notPlain = [
    ['a double-quoted description', '"Does alpha."'],
    ['a single-quoted description', "'Does alpha.'"],
    ['an empty quoted description', '""'],
    ['a description that is only a comment', '# Does alpha.'],
    ['a description that is null', 'null'],
    ['a description that is Null', 'Null'],
    ['a description that is NULL', 'NULL'],
    ['a description that is ~', '~'],
    ['a description that is true', 'true'],
    ['a description that is True', 'True'],
    ['a description that is false', 'false'],
    ['a description that is FALSE', 'FALSE'],
    ['a description that is an integer', '42'],
    ['a description that is a negative integer', '-7'],
    ['a description that is a decimal', '3.14'],
    ['a description that is a number with an exponent', '1e3'],
    ['a description that is a hexadecimal number', '0x1F'],
    ['a description that is an octal number', '0o17'],
    ['a description that is infinity', '.inf'],
    ['a description that is not-a-number', '.nan'],
    ['a description that starts with [', '[Does alpha]'],
    ['a description that starts with {', '{Does: alpha}'],
    ['a description that starts with &', '&anchor Does alpha.'],
    ['a description that starts with *', '*alias'],
    ['a description that starts with !', '!tag Does alpha.'],
    ['a description that starts with %', '%Does alpha.'],
    ['a description that starts with @', '@Does alpha.'],
    ['a description that starts with a backtick', '`Does alpha.'],
    ['a description that starts with a list dash and a space', '- Does alpha.'],
    ['a description that holds ": "', 'Does alpha: it works.'],
    ['a description that holds " #"', 'Does alpha # it works.'],
    ['a description that holds ":" and a tab', 'Does alpha:\tit works.'],
    ['a description that holds a tab and "#"', 'Does alpha\t# it works.'],
    ['a description that ends with ":"', 'Does alpha:'],
  ];
  for (const [what, value] of notPlain) rejects(what, 'alpha', withDescription(value), /description/);
  rejects('a description continued after a blank line', 'alpha', '---\nname: alpha\ndescription: Does alpha\n\n  and more.\n---\n\nText.\n', /one line/);
  rejects('a description continued after a comment line', 'alpha', '---\nname: alpha\ndescription: Does alpha\n# note\n  and more.\n---\n\nText.\n', /one line/);
  rejects('a name continued after a blank line', 'alpha', '---\nname: alpha\n\n  more\ndescription: Does alpha.\n---\n\nText.\n', /one line/);
  rejects('a description given twice, the second as null', 'alpha', '---\nname: alpha\ndescription: Good\ndescription: null\n---\n\nText.\n', /description.*(twice|more than once|duplicate)|(twice|more than once|duplicate).*description/i);
  rejects('a name given twice with different values', 'alpha', '---\nname: alpha\nname: beta\ndescription: Does alpha.\n---\n\nText.\n', /name.*(twice|more than once|duplicate)|(twice|more than once|duplicate).*name/i);
  rejects('a name that is null', 'null', '---\nname: null\ndescription: Does it.\n---\n\nText.\n', /name/);
  rejects('a name that is true', 'true', '---\nname: true\ndescription: Does it.\n---\n\nText.\n', /name/);
  rejects('a name that is a number', '42', '---\nname: 42\ndescription: Does it.\n---\n\nText.\n', /name/);
  rejects('a space before the colon of a second description', 'alpha', '---\nname: alpha\ndescription: Good\ndescription : null\n---\n\nText.\n', /description/);
  rejects('a quoted key as a second description', 'alpha', '---\nname: alpha\ndescription: Good\n"description": null\n---\n\nText.\n', /description/);
  rejects('a name key with no space after the colon', 'alpha', '---\nname:alpha\ndescription: Does alpha.\n---\n\nText.\n', /name/);
  rejects('a description key with no space after the colon', 'alpha', '---\nname: alpha\ndescription:Good\n---\n\nText.\n', /description/);
  rejects('another key given twice', 'alpha', '---\nname: alpha\ndescription: Does alpha.\nlicense: MIT\nlicense: MIT\n---\n\nText.\n', /license/);

  test('accepts another key beside name and description', () => {
    assert.doesNotThrow(() => skillPointer('alpha', '---\nname: alpha\ndescription: Does alpha.\nlicense: MIT\n---\n\nText.\n'));
  });
  for (const value of ['Does alpha. Use it when asked.', 'Does 42 things', 'nullable and truest', '-dashes are fine', 'a:b and a#b', 'It\'s fine and "quoted" inside', 'Use `code` here', 'version 1.2.3', 'yes']) {
    test(`accepts the plain description "${value}"`, () => {
      assert.doesNotThrow(() => skillPointer('alpha', withDescription(value)));
    });
  }
});

describe('skill pointers (integration)', () => {
  const skills = { alpha: skillText('alpha'), beta: skillText('beta') };

  test('writes a pointer for each skill in .agents/skills/ and reports it', (t) => {
    const files = fixture(t, { helper: role }, skills);
    const result = files.run();
    succeeds(result);
    for (const name of ['alpha', 'beta']) {
      const pointer = files.read(...pointerPath(name));
      assert.ok(pointer.startsWith(`---\n# Generated by .agents/generate.mjs from .agents/skills/${name}/SKILL.md`));
      assert.ok(pointer.includes(`\nname: ${name}\n`));
      assert.ok(pointer.includes(`\nlicense: MIT\n`));
      assert.ok(!pointer.includes('Secret instructions'));
      assert.ok(result.stdout.includes(`wrote .claude/skills/${name}/SKILL.md`));
    }
  });

  test('leaves the source skill untouched and writes no skill files for Codex or Copilot', (t) => {
    const files = fixture(t, { helper: role }, skills);
    succeeds(files.run());
    assert.deepEqual(readdirSync(files.path('.github')), ['agents']);
    assert.deepEqual(readdirSync(files.path('.codex')), ['agents']);
    assert.deepEqual(readdirSync(files.path('.agents', 'skills')).sort(), ['alpha', 'beta']);
    assert.equal(files.read('.agents', 'skills', 'alpha', 'SKILL.md'), skills.alpha);
  });

  test('accepts current pointers in check mode and writes nothing', (t) => {
    const files = fixture(t, { helper: role }, skills);
    succeeds(files.run());
    succeeds(files.run('--check'));
  });

  test('check mode reports a missing, an outdated, and a stale pointer without writing', (t) => {
    const files = fixture(t, { helper: role }, { ...skills, gone: skillText('gone') });
    succeeds(files.run());
    rmSync(files.path(...pointerPath('alpha')));
    files.write(['.agents', 'skills', 'beta', 'SKILL.md'], skillText('beta').replace('Does beta work.', 'Does something else.'));
    rmSync(files.path('.agents', 'skills', 'gone'), { recursive: true });

    const result = files.run('--check');
    assert.equal(result.status, 1, result.stderr);
    assert.match(result.stderr, /out of date: \.claude\/skills\/alpha\/SKILL\.md/);
    assert.match(result.stderr, /out of date: \.claude\/skills\/beta\/SKILL\.md/);
    assert.match(result.stderr, /stale: \.claude\/skills\/gone\/SKILL\.md/);
    assert.equal(existsSync(files.path(...pointerPath('alpha'))), false);
    assert.ok(!files.read(...pointerPath('beta')).includes('Does something else.'));
    assert.equal(existsSync(files.path(...pointerPath('gone'))), true);
  });

  test('rewrites an outdated pointer when the source frontmatter changes', (t) => {
    const files = fixture(t, { helper: role }, skills);
    succeeds(files.run());
    files.write(['.agents', 'skills', 'beta', 'SKILL.md'], skillText('beta').replace('license: MIT', 'license: Apache-2.0'));
    succeeds(files.run());
    assert.ok(files.read(...pointerPath('beta')).includes('\nlicense: Apache-2.0\n'));
    succeeds(files.run('--check'));
  });

  test('removes a stale pointer and its folder but keeps a skill in .claude/skills/ it did not write', (t) => {
    const files = fixture(t, { helper: role }, { ...skills, gone: skillText('gone') });
    succeeds(files.run());
    mkdirSync(files.path('.claude', 'skills', 'manual'), { recursive: true });
    files.write(pointerPath('manual'), '---\nname: manual\ndescription: Written by hand.\n---\n\nHand-written instructions.\n');
    rmSync(files.path('.agents', 'skills', 'gone'), { recursive: true });

    succeeds(files.run());
    assert.equal(existsSync(files.path('.claude', 'skills', 'gone')), false);
    assert.ok(files.read(...pointerPath('manual')).includes('Hand-written instructions.'));
    assert.equal(existsSync(files.path(...pointerPath('alpha'))), true);
    succeeds(files.run('--check'));
  });

  test('writes no skill output and no error when there is no .agents/skills/ folder', (t) => {
    const files = fixture(t);
    succeeds(files.run());
    assert.equal(existsSync(files.path('.claude', 'skills')), false);
    succeeds(files.run('--check'));
  });

  test('rejects a skill folder without SKILL.md before writing any file, agent files included', (t) => {
    const files = fixture(t, { helper: role }, { alpha: skillText('alpha'), empty: null });
    rejectsBeforeWriting(files, files.run(), /empty/);
    assert.equal(existsSync(files.path('.claude', 'skills')), false);
  });

  test('rejects an invalid skill before writing any file, agent files included', (t) => {
    const files = fixture(t, { helper: role }, { alpha: skillText('alpha'), beta: '---\nname: beta\n---\n\nNo description.\n' });
    rejectsBeforeWriting(files, files.run(), /beta.*description|description.*beta/);
    assert.equal(existsSync(files.path('.claude', 'skills')), false);
  });

  test('rejects a skill whose description YAML would read as null before writing any file, agent files included', (t) => {
    const files = fixture(t, { helper: role }, { alpha: skillText('alpha'), beta: '---\nname: beta\ndescription: null\n---\n\nText.\n' });
    rejectsBeforeWriting(files, files.run(), /beta.*description|description.*beta/);
    assert.equal(existsSync(files.path('.claude', 'skills')), false);
  });
});
